"""Base adapter interface for OWASP Agentic Threat Auditor (OATA)."""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from oata.core.models import TargetConfig


class AgentResponse(BaseModel):
    """Normalized response representation emitted by an agent target."""
    raw_text: str = Field(default="", description="Textual response generated by the agent")
    tool_calls: List[Dict[str, Any]] = Field(default_factory=list, description="Tool calls issued by agent runtime")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Execution metadata, latency, tokens")


class BaseAdapter(ABC):
    """Abstract driver interface for interacting with agent execution runtimes."""

    def __init__(self, config: TargetConfig):
        self.config = config

    @abstractmethod
    async def connect(self) -> None:
        """Initialize connection or verify target availability."""
        pass

    @abstractmethod
    async def execute_prompt(self, prompt: str, session_context: Optional[Dict[str, Any]] = None) -> AgentResponse:
        """Send a test payload prompt to the agent target and retrieve output & tool calls."""
        pass

    @abstractmethod
    async def close(self) -> None:
        """Tear down sessions, connections, or subprocesses."""
        pass

